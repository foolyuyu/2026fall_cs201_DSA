//
// • 对于 1 ≤ i ≤ |S| - |T| + 1，P[i] = 1 当且仅当 T 作为子串恰好从 S 的下标 i 开始出现；
//
// • 对于 |S| - |T| + 1 < i ≤ |S|，P[i] = 0。
//
// 若满足条件的 T 存在，输出任意一个长度不超过 10^(6)+1 的 T（这样的 T 一定存在），否则输出 -1。
//
// 输入
// 第一行一个由小写英文字母构成的字符串 S (1 ≤ |S| ≤ 10^(6))。
// 第二行一个与 S 等长的 01 串 P。
//
// 输出
// 输出一个字符串 T 或 -1。如果有多种可能的 T，你可以任意输出一种。T必须仅包含英文小写字母。
//
// 样例输入
// 样例1：
// baaababaab
// 0001010000
//
// 样例2：
// zqjzqj
// 000000
//
// 样例3：
// zqjzqj
// 100001
//
// 样例输出
