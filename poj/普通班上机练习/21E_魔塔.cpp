// 描述
// negii在玩一个叫魔塔的游戏，这里我们的游戏略有不同。
//
// 这里的地图是一个由n个点，m条边构成的无向连通图。negii现在在起点的位置，他需要到达每一个点之后才算游戏通关。
//
// 但是，每一条边上都有一个守卫，需要杀死他之后才能通过。
//
// 每个守卫都有一定的攻击力和防御力，negii需要保证的是他的攻击力不小于对方的防御力，并且他的防御力不小于对方的攻击力，这样他才能打败当前的守卫。
//
// 游戏最开始，negii的攻击力和防御力都为0，他需要通过金币购买来提升能力，negii每提升一点攻击力需要花费A个金币，每提升一点防御力需要B个金币，现在他想知道最少他需要花费多少金币才能通关。
//
// 输入
// 第一行，两个数 n, m。
// 第一行，两个数 A, B。
// 接下来m行，每行4个数x,y,v,w，表示x,y之间存在一条有着防御力为v，攻击力为w的守卫的边。
//
// 输出
// 一行，输出一个数，表示答案。
// 如果不存在，请输出-1。
//
// 样例输入
// 3 3
// 2 1
// 1 2 10 5
// 1 2 4 10
// 1 3 5 1
//
// 样例输出
// 20
//
// 提示
// 对于前40%：n<=100，m<=1500
// 对于前70%：数据保证没有重边
// 对于100%：2<=n<=200，1<=m<=50000，A,B,v,w<=10^(9)
