// 描述
// 给出一个长度为N的非负整数序列A，对于所有1≤k≤(N+1)/2，输出A_(1), A_(1)∼A_(3), …, A_(1)∼A_(2k−1)的中位数。即前1,3,5,...个数的中位数。中位数是指将一组数据从小到大排列后，位于中间的那个数。
//
// 输入
// 第1行为一个正整数N，表示了序列长度。第2行包含N个非负整数A_(i)(A_(i) ≤ 10^(9))。
//
// 输出
// 共(N+1)/2行，分别为前1,3,5,...个数的中位数。
//
// 样例输入
// 7
// 1 3 5 7 9 11 6
//
// 样例输出
// 1
// 3
// 5
// 6
//
// 提示
// 对于20%的数据，N ≤ 100；
// 对于40%的数据，N ≤ 3000；
// 对于100%的数据，N ≤ 100000;

