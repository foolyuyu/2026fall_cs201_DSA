// 总时间限制 1000ms  内存限制 131072kB
//
// 描述
// 有N座通信基站，P条双向电缆，第i条电缆连接基站A_(i)和B_(i)。特别地，1号基站是通信公司的总站，N号基站位于一座农场中。现在，农场主希望对通信线路进行升级，其中升级第i条电缆需要花费L_(i)。
//
// 电话公司正在举行优惠活动。农场主可以指定一条从1号基站到N号基站的路径，然后，农场主可以指定路径上不超过K条电缆，先由电话公司免费提供升级服务。农场主只需要支付在该路径上剩余的电缆中，升级价格最贵的那条电缆的花费即可。支付完成后，其余电缆也将由电话公司免费升级。求至少用多少钱能完成升级。
//
// 输入
// 第一行三个整数， N，P，K。
// 接下来P行，每行三个整数A_(i)，B_(i)，L_(i)。
//
// 输出
// 若不存在从1到N的路径，输出-1。否则输出所需最小费用。
//
// 样例输入
// 5 7 1
// 1 2 5
// 3 1 4
// 2 4 8
// 3 2 3
// 5 2 9
// 3 4 7
// 4 5 6
//
// 样例输出
// 4
//
// 提示
// 0 ≤ K < N ≤ 1000
// 1 ≤ P ≤ 2000

