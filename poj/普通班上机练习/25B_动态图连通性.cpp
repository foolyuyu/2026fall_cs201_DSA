//
// 描述
// 有一个 n 个点的无向图，初始没有边。现在执行 q 次加边操作：每次操作给出两个点 u,v 并在图中加入无向边 (u,v)。你需要在每次操作后输出图中有多少对 x,y 满足 1≤x<y≤n，且 x,y 连通（即图中存在 x 到 y 的路径）.
//
// 输入
// 第一行两个正整数 n, q.
// 接下来 q 行每行两个正整数 u, v, 表示加入的边, 保证 1\le u,v\le n.
//
// 输出
// q 行, 每行一个整数, 第 i 行的表示第 i 次加边后的答案.
//
// 样例输入
// 5 5
// 4 1
// 5 2
// 4 5
// 5 4
// 4 3
//
// 样例输出
// 1
// 2
// 6
// 6
// 10
//
// 提示
// 对所有数据 n\le 2\times 10^5, q\le 2\times 10^5.
// 对 30% 的数据: n\le 100.
// 对 60% 的数据: n\le 1000.

