// 总时间限制 10000ms  单个测试点时间限制 1000ms  内存限制 524288kB
//
// 描述
// 对于一棵树 T，你需要给它加一些边，使得它成为一张完全图 G（完全图指的是每两个点之间有一条边的无向图），使它的每条边边权都是整数，边权总和最小，且 G 的唯一最小生成树是 T。
//
// 对于 20% 的数据，N≤10。
// 对于 50% 的数据，N≤1000。
// 对于 100% 的数据，N≤100000, 1≤d[i]≤100000.
//
// 输入
// 第一行 N 表示树 T 的点数
// 接下来 N-1 行每行三个整数 s[i] t[i] d[i]，表示 T 中有一条连接 s[i] 和 t[i] 且权值为 d[i] 的无向边。
// 数据保证输入构成一棵树。
//
// 输出
// 输出仅一个数，表示最小的完全图 G 的边权和。
//
// 样例输入
// 4
// 1 2 1
// 1 3 1
// 1 4 2
//
// 样例输出
// 12
//
// 提示
// 样例解释：添加 d(2,3)=2, d(3,4)=3, d(2,4)=3 即可。
// 注意答案可能会大于 32 位整数的存储范围。

