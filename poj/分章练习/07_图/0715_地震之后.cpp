//
// 　　总结一下,为了求一个图的最小树形图,先求出最短弧集合E0.如果E0不存在,则图的最小树形图也不存在.如果E0存在且不具有环,则E0就是最小树形图.如果E0存在但是存在有向环,则把这个环收缩成一个点u,形成新的图G1,然后对于G1继续求其的最小树形图,直到求到图Gi.如果Gi不具有最小树形图,那么此图不存在最小树形图,如果Gi存在最小树形图,那么逐层展开,就得到了原图的最小树形图.
