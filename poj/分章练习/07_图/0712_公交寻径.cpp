// 0712 公交寻径（全局题号 5445）
// http://dsa.openjudge.cn/graph/0712/
// 总时间限制 5000ms  内存限制 5000kB
//
// 描述
// 小明要坐公交从A站到B站，但是他并不清楚具体的路线应该怎么走，很不幸小明的手机流量用完了不能上网查询，现在他只能依靠手中一份本市公交指南自己找出一条最短的路。
// 已知地图中有N个公交站，有M条公交车线路，其中每条公交车线路m会依次经过km个公交站，假定公交车每前进一站需要5分钟，每次公交车换乘需要10分钟。请帮助小明计算最短路径的耗时（计算耗时从第一次上车开始，即始发站不需要计算等待耗时）。公交站和线路编号均从1开始。注意公交线路中并没有环线。〔原题配图 http://media.openjudge.cn/images/upload/1354013978.jpg〕
//
// 输入
// 第一行输入整数N表示公交站数，M表示公交线路数，100>N>1, 20>M>0。
// 第二行输入整数A，B，分别表示起点和终点，N>=A>0，N>=B>0。
// 之后输入M行，表示每一条公交线路经过站点情况。其中对每一个公交线路m，首先输入一个整数km>1，表示第m条公交车线路一共经过的站数，之后接km个整数，表示这km个站点的序号。
//
// 输出
// 输出：整数T，最短路径耗时（分钟）。如果路线不通，输出-1。
//
// 样例输入
// 7 4
// 1 7
// 2 1 2
// 3 2 3 4
// 3 4 5 6
// 2 6 7
//
// 样例输出
// 60

