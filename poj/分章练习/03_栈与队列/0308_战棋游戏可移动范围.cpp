// 0308 战棋游戏可移动范围（全局题号 7205）
// http://dsa.openjudge.cn/stack/0308/
// 总时间限制 1000ms  内存限制 65536kB
//
// 描述
// 在战棋游戏中，一个角色的移动力是有限的。能否从一个格子移动到另一个格子，取决于其移动力以及敌我军的情况。现在给定一张棋盘，标明敌军与我军的位置，请标明棋盘上的每一个格子需要用几步可以达到。这时，需要考虑在战棋中的ZOC规则，即“控制领域规则”。它表示，敌军会控制它周身上下左右四个位置，如果我军移动到该位置，就不能继续移动
// 如下图，对于棋盘：
// O　O　O　O
// O　O　O　O
// X　O　B　O
//
// O表示空位，X表示要移动的部队，B表示敌军，那么到达各个位置需要占用的移动力为（-1表示不可到达）：
// 2　3　4　5
// 1　2　3　6
// 0　1 -1　7
// 很明显，B位置的上面一格是被控制的，所以从数字3的地方，不能直接到达数字6的地方，也就是说，只能从上面绕过去
//
// 但是，有的时候，并非所有的地形消耗都是1.比如说，对于骑兵来说，它们在平原的地形消耗为1，在荒地的地形消耗为2，在山地的地形消耗为3.也就是说，如果骑兵的移动力为6，那么它们走平原可以只6格，但是走山地只能走两格。
//
// 说明：该角色移动一步，就会消耗一定的移动力。部队只允许往上下左右四个方向移动。我军的部队可以“穿过”，但是不允许“占据”其位置。敌军部队不可以“穿过”，更不允许占据其位置，而且考虑ZOC规则。
//
// 输入
// 输入分成两个部分
// 第一部分是两个整数，X与Y，分别表示地图的行与列(X<100,Y<100)
// 第二部分是一个中间没有空格的矩阵，1到3的数字表示棋盘上的空位对该兵种所需要消耗的移动力，X表示要移动的角色，A表示我军，设我军所占位置仅消耗1的移动力，B表示敌军，*表示障碍物
//
// 输出
// 输出显示要达到该点需要的移动力，如果无法达到，则显示-1。每个数字占两格位置
//
// 样例输入
// 5　9
// 111111*12
// 122211*21
// 1A11111**
// 12211B111
// 1X1131111
//
// 样例输出
//  5 6 7 7 7 8-1-1-1
//  4 5 6 6 6 7-1-1-1
//  3-1 4 4 5 6-1-1-1
//  2 2 3 3 4-1-1-1-1
//  1 0 1 2 5 6-1-1-1

