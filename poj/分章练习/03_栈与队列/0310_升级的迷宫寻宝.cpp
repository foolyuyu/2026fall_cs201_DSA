// 0310 升级的迷宫寻宝（全局题号 7209）
// http://dsa.openjudge.cn/stack/0310/
// 总时间限制 1000ms  内存限制 65535kB
//
// 描述
// 给定一张地图，人物只能走上下左右，给定入口与出口，但有个问题
// 要达到出口时，必须拿到钥匙，才能过关
// 钥匙掉落在迷宫中，你需要从中捡取
// 求拿钥匙并走出迷宫的最快路线
//
// 输入
// 输入分为两个部分
// 第一部分是两个整数X与Y，X<100,Y<100，表示迷宫的行与列
// 第二部分是迷宫地图，1表示障碍，0表入可走，R表示入口，C表示出口，Y表示钥匙
//
// 输出
// 拿到钥匙并走出迷宫的最快路线（最左上角坐标为1，1）
//
// 样例输入
// 5 7
// 1R10001
// 1010101
// 1000011
// 101100C
// 1Y00011
//
// 样例输出
// 1 2
// 2 2
// 3 2
// 4 2
// 5 2
// 5 3
// 5 4
// 5 5
// 4 5
// 4 6
// 4 7

